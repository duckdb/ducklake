    lines.append("// Server")
    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    commit = spec.commit_endpoint
    for endpoint in spec.routed:
        lines.append(
            f"static string {endpoint.cpp_name}Endpoint(DuckLakeRESTRequest &request, const string &body) {{"
        )
        lines.append(
            f"\tauto parameters = DuckLakeRESTSerializer::ReadRequest<{endpoint.request.cpp_name}>(request, body);"
        )
        if endpoint.response:
            lines.append(
                f"\tauto result = DuckLakeRESTEndpoints::{endpoint.cpp_name}(request, parameters);"
            )
            lines.append(
                "\treturn DuckLakeRESTSerializer::ToResponse(request, result);"
            )
        else:
            lines.append(
                f"\tDuckLakeRESTEndpoints::{endpoint.cpp_name}(request, parameters);"
            )
            lines.append('\treturn "{}";')
        lines.append("}")
        lines.append("")
    lines.append(
        "const unordered_map<string, rest_endpoint_t> &DuckLakeRESTAPI::GetEndpoints() {"
    )
    lines.append("\tstatic const unordered_map<string, rest_endpoint_t> endpoints = {")
    for endpoint in spec.routed:
        lines.append(
            f"\t    {{{cpp_string(endpoint.name)}, {endpoint.cpp_name}Endpoint}},"
        )
    lines.append("\t};")
    lines.append("\treturn endpoints;")
    lines.append("}")
    lines.append("")
    lines.append("const vector<RESTRoute> &DuckLakeRESTAPI::GetRoutes() {")
    lines.append("\tstatic const vector<RESTRoute> routes = {")
    for endpoint in spec.routed:
        parameters = ", ".join(
            "{{{}, RESTParameterType::{}, {}}}".format(
                cpp_string(p["name"]),
                spec.parameter_type(p["type"]),
                cpp_string(p.get("query_name", "")),
            )
            for p in endpoint.parameters
        )
        lines.append(
            f"\t    {{{cpp_string(endpoint.name)}, {cpp_string(endpoint.method)}, {cpp_string(endpoint.path)}, {{{parameters}}}"
            + (", true" if endpoint.no_prefix else "")
            + "},"
        )
    lines.append("\t};")
    lines.append("\treturn routes;")
    lines.append("}")
    lines.append("")
    lines.append("const RESTRoute &DuckLakeRESTAPI::GetRoute(const string &endpoint) {")
    lines.append("\tfor (auto &route : GetRoutes()) {")
    lines.append("\t\tif (route.endpoint == endpoint) {")
    lines.append("\t\t\treturn route;")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append(
        '\tthrow InternalException("DuckLake REST: unknown endpoint \\"%s\\"", endpoint);'
    )
    lines.append("}")
    lines.append("")

    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    lines.append("// Client")
    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    for endpoint in spec.routed:
        response = endpoint.response
        result = response.cpp_name if response else "void"
        lines.append(
            f"{result} DuckLakeRESTClientAPI::{endpoint.cpp_name}(const {endpoint.request.cpp_name} &request) {{"
        )
        lines.append("\tRESTPathScope paths(GetPathMapper());")
        idempotent = "true" if endpoint.idempotent else "false"
        lines.append("\tauto context = GetContext();")
        lines.append("\tvector<RESTBodyPart> parts;")
        lines.append("\tDuckLakeRESTSerializer::AddParts(*context, request, parts);")
        post = f"Call({cpp_string(endpoint.name)}, DuckLakeRESTSerializer::ToJSON(request), {idempotent}, parts)"
        if response:
            lines.append(f"\tauto response = {post};")
            lines.append("\tresponse.context = context.get();")
            lines.append(
                f"\treturn DuckLakeRESTSerializer::ReadResponse<{response.cpp_name}>(response);"
            )
        else:
            lines.append(f"\t{post};")
        lines.append("}")
        lines.append("")
    lines.append("} // namespace duckdb")
    return "\n".join(lines) + "\n"


