class Field:
    def __init__(self, spec, owner):
        self.spec = spec
        self.owner = owner
        if "name" not in spec or "type" not in spec:
            raise SpecError(f'{owner}: fields need a "name" and a "type"')
        self.name = spec["name"]
        self.type_text = spec["type"]
        self.type = parse_type(spec["type"])
        self.member = spec.get("member", self.name)
        self.nullable = spec.get("nullable", False)
        self.default = spec.get("default")
        self.has_member = spec.get("has_member")
        self.null_member = spec.get("null_member")
        self.key_field = spec.get("key_field")
        self.value_field = spec.get("value_field")
        self.cpp_type = spec.get("cpp_type")
        self.row_types = spec.get("row_types")
        self.arrow_only = spec.get("arrow_only")
        self.description = description_text(spec)
        known = {
            "name",
            "type",
            "description",
            "member",
            "nullable",
            "default",
            "has_member",
            "null_member",
            "key_field",
            "value_field",
            "cpp_type",
            "row_types",
            "arrow_only",
        }
        unknown = set(spec.keys()) - known
        if unknown:
            raise SpecError(
                f"{owner}.{self.name}: unknown field properties {sorted(unknown)}"
            )
        if self.nullable and self.default is not None:
            raise SpecError(
                f"{owner}.{self.name}: a field cannot be nullable and have a default"
            )
        if (self.has_member or self.null_member) and not self.nullable:
            raise SpecError(
                f"{owner}.{self.name}: has_member / null_member require a nullable field"
            )
        if self.type.kind == "map" and not self.key_field:
            raise SpecError(f'{owner}.{self.name}: map fields need a "key_field"')
        if self.key_field and self.type.kind != "map":
            raise SpecError(f'{owner}.{self.name}: only map fields have a "key_field"')
        if (
            self.type.kind == "primitive"
            and self.type.name == "rows"
            and self.arrow_only
        ):
            pass
        elif (self.type.kind == "primitive" and self.type.name == "rows") != (
            self.row_types is not None
        ):
            raise SpecError(
                f'{owner}.{self.name}: rows fields need "row_types", and only they can have it'
            )


class ObjectType:
    def __init__(self, spec, section, is_request=False):
        self.spec = spec
        self.section = section
        self.name = spec["name"]
        self.description = description_text(spec)
        self.cpp_class = spec.get("class")
        self.extends = spec.get("extends")
        self.custom = spec.get("custom", False)
        self.null_if = spec.get("null_if")
        self.variant_of = spec.get("variant_of")
        self.is_request = is_request
        self.commit_request = None
        self.fields = [Field(field, self.name) for field in spec.get("fields", [])]
        known = {
            "name",
            "description",
            "class",
            "extends",
            "custom",
            "null_if",
            "fields",
            "variant_of",
        }
        unknown = set(spec.keys()) - known
        if unknown:
            raise SpecError(f"{self.name}: unknown type properties {sorted(unknown)}")

    @property
    def is_bound(self):
        return self.cpp_class is not None

    @property
    def cpp_name(self):
        return self.cpp_class if self.cpp_class else "REST" + self.name


class UnionType:
    """A tagged union of structures, which is an object with exactly one member: the name of the variant"""

    def __init__(self, spec, section):
        self.spec = spec
        self.section = section
        self.name = spec["name"]
        self.description = description_text(spec)
        self.variants = [
            (variant["name"], variant["type"]) for variant in spec["variants"]
        ]

    @property
    def cpp_name(self):
        return "REST" + self.name

    @property
    def type_enum(self):
        return f"REST{self.name}Type"

    @property
    def codec(self):
        return f"REST{self.name}Codec"


class EnumType:
    def __init__(self, spec, section):
        self.spec = spec
        self.section = section
        self.name = spec["name"]
        self.description = description_text(spec)
        self.cpp_enum = spec.get("enum")
        self.values = spec["values"]
        for value in self.values:
            if "name" not in value:
                raise SpecError(f'{self.name}: enum values need a "name"')
            if self.cpp_enum and "cpp" not in value:
                raise SpecError(
                    f'{self.name}: values of enums that are bound to a C++ enum need a "cpp" name'
                )

    @property
    def cpp_name(self):
        return self.cpp_enum if self.cpp_enum else "string"

    @property
    def codec(self):
        return f"REST{self.name}Codec"


class Endpoint:
    def __init__(self, spec, section):
        self.spec = spec
        self.section = section
        self.name = spec["name"]
        self.kind = spec["kind"]
        if self.kind not in ENDPOINT_KINDS:
            raise SpecError(f"{self.name}: kind has to be one of {ENDPOINT_KINDS}")
        self.summary = spec.get("summary", "")
        self.idempotent = spec.get("idempotent", False)
        self.description = description_text(spec)
        self.cpp_name = spec.get("cpp_name", pascal_case(self.name))
        self.method = spec.get("method")
        self.path = spec.get("path")
        self.parameters = spec.get("parameters", [])
        self.no_prefix = spec.get("no_prefix", False)
        if self.kind != "commit" and (not self.method or not self.path):
            raise SpecError(f"{self.name}: endpoints need a method and a path")
        self.request = self.body(spec.get("request", {}), "Request", section)
        self.response = (
            self.body(spec["response"], "Response", section)
            if "response" in spec
            else None
        )
        self.owned = [
            body
            for body in (self.request, self.response)
            if isinstance(body, ObjectType)
        ]
        if self.kind == "commit":
            if not isinstance(self.request, ObjectType):
                raise SpecError(
                    f"{self.name}: commit requests need a request structure of their own"
                )
            self.request.commit_request = self
        known = {
            "name",
            "kind",
            "summary",
            "description",
            "cpp_name",
            "request",
            "response",
            "idempotent",
            "method",
            "path",
            "parameters",
            "no_prefix",
        }
        unknown = set(spec.keys()) - known
        if unknown:
            raise SpecError(
                f"{self.name}: unknown endpoint properties {sorted(unknown)}"
            )

    def body(self, spec, suffix, section):
        """The request or response of an endpoint: a structure of its own, or a type of the specification"""
        if "type" in spec:
            if len(spec) != 1:
                raise SpecError(
                    f"{self.name}: a {suffix.lower()} that refers to a type cannot have other properties"
                )
            return spec["type"]
        spec = dict(spec)
        spec["name"] = self.cpp_name + suffix
        return ObjectType(spec, section, is_request=suffix == "Request")

    def own_bodies(self):
        return self.owned


class Section:
    def __init__(self, title, spec):
        self.title = title
        self.description = description_text(spec)
        self.includes = spec.get("includes", [])
        self.types = []
        for entry in spec.get("types", []):
            if "values" in entry:
                self.types.append(EnumType(entry, self))
            elif "variants" in entry:
                self.types.append(UnionType(entry, self))
            else:
                self.types.append(ObjectType(entry, self))
        self.endpoints = [Endpoint(entry, self) for entry in spec.get("endpoints", [])]


class Spec:
    def __init__(self, section_specs):
        self.sections = [Section(name, data) for name, data in section_specs]
        self.types = {}
        self.objects = []
        self.enums = []
        self.unions = []
        for section in self.sections:
            for entry in section.types:
                if entry.name in self.types:
                    raise SpecError(f'Duplicate type "{entry.name}"')
                self.types[entry.name] = entry
                if isinstance(entry, EnumType):
                    self.enums.append(entry)
                elif isinstance(entry, UnionType):
                    self.unions.append(entry)
                else:
                    self.objects.append(entry)
        self.endpoints = [
            endpoint for section in self.sections for endpoint in section.endpoints
        ]
        names = set()
        for endpoint in self.endpoints:
            if endpoint.name in names:
                raise SpecError(f'Duplicate endpoint "{endpoint.name}"')
            names.add(endpoint.name)
        self.commit_endpoint = next(
            (e for e in self.endpoints if e.name == COMMIT_ENDPOINT), None
        )
        if not self.commit_endpoint:
            raise SpecError(f'The specification has no "{COMMIT_ENDPOINT}" endpoint')
        self.commit_requests = [
            endpoint for endpoint in self.endpoints if endpoint.kind == "commit"
        ]
        self.routed = [
            endpoint for endpoint in self.endpoints if endpoint.kind != "commit"
        ]
        for endpoint in self.endpoints:
            if isinstance(endpoint.request, str):
                endpoint.request = self.lookup_object(endpoint.request, endpoint.name)
            if isinstance(endpoint.response, str):
                endpoint.response = self.lookup_object(endpoint.response, endpoint.name)
        if self.commit_endpoint.kind != "transaction":
            raise SpecError(f'"{COMMIT_ENDPOINT}" has to be of kind "transaction"')
        self.validate()
        for endpoint in self.routed:
            self.validate_route(endpoint)

    def parameter_type(self, type_text):
        """The C++ enumerator of a parameter of the URL: enums that are strings on the wire are strings"""
        if type_text in PARAMETER_TYPES:
            return PARAMETER_TYPES[type_text]
        entry = self.types.get(type_text)
        if isinstance(entry, EnumType) and not entry.cpp_enum:
            return "STRING"
        return None

    def validate_route(self, endpoint):
        fields = {field.name: field for field in self.fields_of(endpoint.request)}
        seen = set()
        for parameter in endpoint.parameters:
            name = parameter["name"]
            if name not in fields or name in seen:
                raise SpecError(f"{endpoint.name}: unknown parameter {name}")
            seen.add(name)
            if self.parameter_type(parameter["type"]) is None:
                raise SpecError(
                    f"{endpoint.name}.{name}: parameters of the URL cannot be of type {parameter['type']}"
                )
            if parameter["location"] == "path" and (
                fields[name].nullable or fields[name].default is not None
            ):
                raise SpecError(f"{endpoint.name}.{name}: labels have to be required")
        if endpoint.method == "GET" and set(fields) - seen:
            raise SpecError(f"{endpoint.name}: all members of a GET are parameters")

    def lookup_object(self, name, context):
        result = self.lookup(name, context)
        if not isinstance(result, ObjectType):
            raise SpecError(f"{context}: {name} is not an object type")
        return result

    def all_objects(self):
        result = list(self.objects)
        for endpoint in self.endpoints:
            result.extend(endpoint.own_bodies())
        return result

    def lookup(self, name, context):
        if name not in self.types:
            raise SpecError(f'{context}: unknown type "{name}"')
        return self.types[name]

    def validate(self):
        for union in self.unions:
            for wire_name, struct_name in union.variants:
                variant = self.lookup_object(struct_name, union.name)
                if (
                    variant.variant_of != (union.name, wire_name)
                    or variant.is_bound
                    or variant.extends
                ):
                    raise SpecError(
                        f"{union.name}: {struct_name} has to be an unbound structure without a mixin"
                    )
        classes = {}
        for obj in self.all_objects():
            if obj.cpp_class:
                if obj.cpp_class in classes:
                    raise SpecError(
                        f"{obj.name}: class {obj.cpp_class} is already bound to {classes[obj.cpp_class]}"
                    )
                classes[obj.cpp_class] = obj.name
            if obj.extends:
                base = self.lookup(obj.extends, obj.name)
                if not isinstance(base, ObjectType):
                    raise SpecError(f"{obj.name}: can only extend object types")
                if base.is_bound != obj.is_bound:
                    raise SpecError(
                        f"{obj.name}: bound types can only extend bound types, and DTOs DTOs"
                    )
            names = set()
            for field in self.fields_of(obj):
                if field.name in names:
                    raise SpecError(f'{obj.name}: duplicate field "{field.name}"')
                names.add(field.name)
                self.validate_type(field.type, f"{obj.name}.{field.name}")
                if field.nullable and not obj.is_bound and not field.cpp_type:
                    # make sure the field has a C++ type that can be null
                    self.cpp_type(field)
                if field.row_types:
                    base_name = field.row_types.split(".")[0]
                    if base_name not in names:
                        raise SpecError(
                            f'{obj.name}.{field.name}: row_types refers to "{base_name}", which has to '
                            f"be a field that precedes it"
                        )

    def validate_type(self, expr, context):
        if expr.kind == "named":
            self.lookup(expr.name, context)
        for arg in expr.args:
            self.validate_type(arg, context)

    def fields_of(self, obj):
        fields = []
        if obj.extends:
            fields.extend(self.fields_of(self.types[obj.extends]))
        fields.extend(obj.fields)
        return fields

    # ===--------------------------------------------------------------------=== #
    # C++ types and codecs
    # ===--------------------------------------------------------------------=== #
    def codec(self, expr):
        if expr.kind == "primitive":
            return PRIMITIVES[expr.name][0]
        if expr.kind == "list":
            return f"RESTListCodec<{self.codec(expr.args[0])}>"
        if expr.kind == "dict":
            return f"RESTDictCodec<{self.codec(expr.args[0])}>"
        if expr.kind == "map":
            raise SpecError("maps have no codec")
        entry = self.types[expr.name]
        if isinstance(entry, (EnumType, UnionType)):
            return entry.codec
        return f"RESTObjectCodec<{entry.cpp_name}>"

    def cpp_type_of(self, expr, nullable=False):
        if expr.kind == "primitive":
            return PRIMITIVES[expr.name][2 if nullable else 1]
        if expr.kind == "list":
            return f"vector<{self.cpp_type_of(expr.args[0])}>"
        if expr.kind == "dict":
            return f"map<string, {self.cpp_type_of(expr.args[0])}>"
        if expr.kind == "map":
            return f"map<{self.cpp_type_of(expr.args[0])}, {self.cpp_type_of(expr.args[1])}>"
        entry = self.types[expr.name]
        if isinstance(entry, UnionType):
            return f"unique_ptr<{entry.cpp_name}>"
        if isinstance(entry, EnumType):
            if nullable and entry.cpp_enum:
                return f"RESTOptional<{entry.cpp_name}>"
            return entry.cpp_name
        if nullable and not entry.null_if:
            return f"unique_ptr<{entry.cpp_name}>"
        return entry.cpp_name

    def cpp_type(self, field):
        if field.cpp_type:
            return field.cpp_type
        return self.cpp_type_of(field.type, field.nullable)

    def default_literal(self, field):
        """The C++ value of the default of a field, None for an empty container"""
        value = field.default
        expr = field.type
        if expr.kind in ("list", "dict", "map"):
            if value not in ([], {}):
                raise SpecError(
                    f"{field.owner}.{field.name}: containers can only default to an empty container"
                )
            return None
        if expr.kind == "primitive":
            if expr.name == "bool":
                return "true" if value else "false"
            if expr.name in ("uint64", "int64"):
                return str(int(value))
            if expr.name == "double":
                return repr(float(value))
            if expr.name in ("string", "path"):
                return f"string({cpp_string(value)})"
        if expr.kind == "named":
            entry = self.types[expr.name]
            if isinstance(entry, EnumType):
                matches = [v for v in entry.values if v["name"] == value]
                if not matches:
                    raise SpecError(
                        f'{field.owner}.{field.name}: default "{value}" is not a value of {entry.name}'
                    )
                if entry.cpp_enum:
                    return f'{entry.cpp_enum}::{matches[0]["cpp"]}'
                return f"string({cpp_string(value)})"
        raise SpecError(
            f"{field.owner}.{field.name}: defaults are not supported for type {expr}"
        )

    def initializer(self, field):
        if field.default is not None and not field.cpp_type:
            return self.default_literal(field)
        if field.nullable or field.cpp_type:
            return None
        expr = field.type
        if expr.kind == "primitive":
            if expr.name == "bool":
                return "false"
            if expr.name in ("uint64", "int64"):
                return "0"
            if expr.name == "double":
                return "0"
        if expr.kind == "named":
            entry = self.types[expr.name]
            if isinstance(entry, EnumType) and entry.cpp_enum:
                return f'{entry.cpp_enum}::{entry.values[0]["cpp"]}'
        return None

    # ===--------------------------------------------------------------------=== #
    # Documentation of types
    # ===--------------------------------------------------------------------=== #
    def doc_type(self, expr):
        if expr.kind == "primitive":
            return f"`{expr.name}`"
        if expr.kind == "list":
            return f"list of {self.doc_type(expr.args[0])}"
        if expr.kind == "dict":
            return f"object of {self.doc_type(expr.args[0])}"
        if expr.kind == "map":
            return f"list of {self.doc_type(expr.args[1])}"
        return f"[`{expr.name}`](#{expr.name.lower()})"


