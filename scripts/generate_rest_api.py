def find_smithy():
    smithy = os.environ.get("SMITHY") or shutil.which("smithy")
    if not smithy:
        raise SpecError(
            "the Smithy CLI is required to read the specification: install it from "
            "https://smithy.io/2.0/guides/smithy-cli/cli_installation.html, or point SMITHY to it"
        )
    return smithy


def load_smithy_ast(spec_dir):
    """Validates the Smithy model and returns its JSON AST"""
    files = sorted(
        os.path.join(spec_dir, name)
        for name in os.listdir(spec_dir)
        if name.endswith(".smithy")
    )
    smithy = find_smithy()
    validate = subprocess.run(
        [smithy, "validate", "--quiet", *files], capture_output=True, text=True
    )
    if validate.returncode != 0:
        raise SpecError(
            f"the Smithy model is invalid:\n{validate.stdout}{validate.stderr}"
        )
    result = subprocess.run(
        [smithy, "ast", "--quiet", *files], capture_output=True, text=True
    )
    if result.returncode != 0:
        raise SpecError(f"smithy ast failed:\n{result.stdout}{result.stderr}")
    return json.loads(result.stdout)


class SmithyModel:
    """Converts the Smithy model of the API to the sections, types and endpoints of the generator"""

    def __init__(self, ast):
        self.shapes = ast["shapes"]
        services = [
            shape_id
            for shape_id, shape in self.shapes.items()
            if shape["type"] == "service"
        ]
        if len(services) != 1:
            raise SpecError(
                f"the model has to have exactly one service, it has {len(services)}"
            )
        self.service = self.shapes[services[0]]
        if (
            COMMIT_UNION not in self.shapes
            or self.shapes[COMMIT_UNION]["type"] != "union"
        ):
            raise SpecError(f"the model has no union {COMMIT_UNION}")
        # the requests of a commit, by the structure of their parameters
        self.commit_requests = {}
        for name, member in self.shapes[COMMIT_UNION]["members"].items():
            self.commit_requests[member["target"]] = name
        # the variants of the unions other than CommitRequest, by the structure of their parameters
        self.variants = {}
        for shape_id, shape in self.shapes.items():
            if (
                shape["type"] == "union"
                and shape_id.startswith(NAMESPACE + "#")
                and shape_id != COMMIT_UNION
            ):
                for name, member in shape["members"].items():
                    self.variants[member["target"]] = (self.local_name(shape_id), name)
        # the entries of lists that are stored as C++ maps, which are not structures of the generated code
        self.map_entries = set()
        for shape in self.shapes.values():
            for member in shape.get("members", {}).values():
                if self.trait(member, "cppMap") is not None:
                    self.map_entries.add(
                        self.shapes[member["target"]]["member"]["target"]
                    )

    @staticmethod
    def trait(shape, name, default=None):
        traits = shape.get("traits", {})
        if f"{CODEGEN}#{name}" in traits:
            return traits[f"{CODEGEN}#{name}"]
        return traits.get(f"smithy.api#{name}", default)

    @staticmethod
    def local_name(shape_id):
        return shape_id.split("#")[1]

    def documentation(self, shape):
        return self.trait(shape, "documentation", "")

    def type_text(self, target, member=None):
        """The type of a member as a type expression of the generator"""
        if target in SMITHY_PRIMITIVES:
            return SMITHY_PRIMITIVES[target]
        if target == COMMIT_UNION:
            return "commit_request"
        if target not in self.shapes:
            raise SpecError(f"unsupported type {target}")
        shape = self.shapes[target]
        wire_type = self.trait(shape, "wireType")
        if wire_type:
            return wire_type
        if shape["type"] == "list":
            cpp_map = self.trait(member, "cppMap") if member is not None else None
            element = shape["member"]["target"]
            if cpp_map is None:
                return f"list<{self.type_text(element)}>"
            # a list of entries that is stored as a map, by the key field of the entries
            entry = self.shapes[element]
            entry_members = self.all_members(entry)
            key = self.type_text(entry_members[cpp_map["keyField"]]["target"])
            if "valueField" in cpp_map:
                value = self.type_text(entry_members[cpp_map["valueField"]]["target"])
            else:
                value = self.local_name(cpp_map["value"])
            return f"map<{key}, {value}>"
        if shape["type"] == "map":
            return f'dict<{self.type_text(shape["value"]["target"])}>'
        if shape["type"] in ("structure", "enum", "union"):
            return self.local_name(target)
        raise SpecError(f'unsupported shape type {shape["type"]} of {target}')

    def all_members(self, shape):
        result = {}
        for mixin in shape.get("mixins", []):
            result.update(self.all_members(self.shapes[mixin["target"]]))
        result.update(shape.get("members", {}))
        return result

    def fields(self, shape):
        result = []
        for name, member in shape.get("members", {}).items():
            field = {"name": name, "type": self.type_text(member["target"], member)}
            field["description"] = self.documentation(member)
            traits = member.get("traits", {})
            if "smithy.api#default" in traits:
                field["default"] = traits["smithy.api#default"]
            elif "smithy.api#required" not in traits:
                field["nullable"] = True
            for trait, key in MEMBER_TRAITS.items():
                value = self.trait(member, trait)
                if value is not None:
                    field[key] = value
            cpp_map = self.trait(member, "cppMap")
            if cpp_map is not None:
                field["key_field"] = cpp_map["keyField"]
                if "valueField" in cpp_map:
                    field["value_field"] = cpp_map["valueField"]
            result.append(field)
        return result

    def structure(self, shape_id, name=None):
        shape = self.shapes[shape_id]
        result = {
            "name": name or self.local_name(shape_id),
            "description": self.documentation(shape),
        }
        mixins = shape.get("mixins", [])
        if len(mixins) > 1:
            raise SpecError(f"{shape_id}: structures can only have one mixin")
        if mixins:
            result["extends"] = self.local_name(mixins[0]["target"])
        cpp_class = self.trait(shape, "cppClass")
        if cpp_class:
            result["class"] = cpp_class
        null_if = self.trait(shape, "nullIf")
        if null_if:
            result["null_if"] = null_if
        if self.trait(shape, "customSerialization") is not None:
            result["custom"] = True
        if shape_id in self.variants:
            result["variant_of"] = self.variants[shape_id]
        result["fields"] = self.fields(shape)
        return result

    def union(self, shape_id):
        shape = self.shapes[shape_id]
        variants = [
            {"name": name, "type": self.local_name(member["target"])}
            for name, member in shape["members"].items()
        ]
        return {
            "name": self.local_name(shape_id),
            "description": self.documentation(shape),
            "variants": variants,
        }

    def enum(self, shape_id):
        shape = self.shapes[shape_id]
        result = {
            "name": self.local_name(shape_id),
            "description": self.documentation(shape),
            "values": [],
        }
        cpp_class = self.trait(shape, "cppClass")
        if cpp_class:
            result["enum"] = cpp_class
        for name, member in shape["members"].items():
            value = {
                "name": member["traits"]["smithy.api#enumValue"],
                "description": self.documentation(member),
            }
            if cpp_class:
                value["cpp"] = name
            result["values"].append(value)
        return result

    def body(self, operation, key, suffix):
        if key not in operation or operation[key]["target"] == "smithy.api#Unit":
            return None
        target = operation[key]["target"]
        shape = self.shapes[target]
        if "smithy.api#input" in shape.get(
            "traits", {}
        ) or "smithy.api#output" in shape.get("traits", {}):
            body = self.structure(target)
            del body["name"]
            del body["description"]
            return body
        if target in self.commit_requests:
            body = self.structure(target)
            del body["name"]
            return body
        return {"type": self.local_name(target)}

    def kind(self, shape_id, operation):
        input_shape = operation.get("input", {}).get("target")
        if input_shape in self.shapes:
            for member in self.shapes[input_shape].get("members", {}).values():
                target = self.shapes.get(member["target"], {})
                if (
                    target.get("type") == "list"
                    and target["member"]["target"] == COMMIT_UNION
                ):
                    return "transaction"
        if "smithy.api#readonly" in operation.get("traits", {}):
            return "read"
        return "command"

    def route_parameters(self, shape_id, operation, path):
        """The members of the input that are sent in the path or the query of the URL instead of the body"""
        parameters = []
        input_shape = operation.get("input", {}).get("target")
        if input_shape in self.shapes:
            for name, member in self.all_members(self.shapes[input_shape]).items():
                traits = member.get("traits", {})
                type_text = self.type_text(member["target"], member)
                if "smithy.api#httpLabel" in traits:
                    parameters.append(
                        {"name": name, "location": "path", "type": type_text}
                    )
                elif "smithy.api#httpQuery" in traits:
                    parameters.append(
                        {
                            "name": name,
                            "location": "query",
                            "query_name": traits["smithy.api#httpQuery"],
                            "type": type_text,
                        }
                    )
        order = re.findall(r"\{(\w+)\}", path)
        parameters.sort(
            key=lambda p: order.index(p["name"]) if p["location"] == "path" else 1000
        )
        labels = {p["name"] for p in parameters if p["location"] == "path"}
        if labels != set(re.findall(r"\{(\w+)\}", path)):
            raise SpecError(
                f"{shape_id}: the labels of the uri have to match the @httpLabel members"
            )
        return parameters

    def endpoint(self, shape_id):
        operation = self.shapes[shape_id]
        http = self.trait(operation, "http")
        if (
            not http
            or http["method"] not in ("GET", "POST")
            or not re.fullmatch(r"/v1/[a-z0-9{}_/-]+", http["uri"])
        ):
            raise SpecError(
                f"{shape_id}: operations need a GET or POST http trait with a /v1/... uri"
            )
        name = snake_case(self.local_name(shape_id))
        documentation = self.documentation(operation)
        summary, _, description = documentation.partition("\n\n")
        result = {
            "name": name,
            "cpp_name": self.local_name(shape_id),
            "kind": self.kind(shape_id, operation),
            "method": http["method"],
            "path": http["uri"],
            "parameters": self.route_parameters(shape_id, operation, http["uri"]),
            "no_prefix": self.trait(operation, "noPrefix") is not None,
            "idempotent": "smithy.api#readonly" in operation.get("traits", {})
            or "smithy.api#idempotent" in operation.get("traits", {}),
            "summary": summary,
            "description": description,
        }
        request = self.body(operation, "input", "Request")
        if request is not None:
            result["request"] = request
        response = self.body(operation, "output", "Response")
        if response is not None:
            result["response"] = response
        return result

    def commit_endpoint(self, member_name, shape_id):
        """The request of a commit, which can only be sent as part of commit_transaction"""
        body = self.structure(shape_id)
        del body["name"]
        summary, _, description = self.documentation(self.shapes[shape_id]).partition(
            "\n\n"
        )
        body["description"] = f"The `{member_name}` request of a commit."
        return {
            "name": member_name,
            "cpp_name": pascal_case(member_name),
            "kind": "commit",
            "idempotent": False,
            "summary": summary,
            "description": description,
            "request": body,
        }

    def sections(self):
        endpoints = [
            self.endpoint(operation["target"])
            for operation in self.service.get("operations", [])
        ]
        for member_name, member in self.shapes[COMMIT_UNION]["members"].items():
            endpoints.append(self.commit_endpoint(member_name, member["target"]))
        excluded = set(self.commit_requests) | self.map_entries | {COMMIT_UNION}
        types = []
        for shape_id, shape in self.shapes.items():
            if not shape_id.startswith(NAMESPACE + "#") or shape_id in excluded:
                continue
            traits = shape.get("traits", {})
            if "smithy.api#input" in traits or "smithy.api#output" in traits:
                continue
            if shape["type"] == "structure":
                types.append(self.structure(shape_id))
            elif shape["type"] == "enum":
                types.append(self.enum(shape_id))
            elif shape["type"] == "union":
                types.append(self.union(shape_id))
        result = []
        for section in self.trait(self.service, "docSections", []):
            data = {
                "section": section["title"],
                "description": section.get("documentation", "").strip(),
            }
            kind = section["kind"]
            if kind == "types":
                data["types"] = types
            else:
                kinds = ("transaction", "commit") if kind == "commit" else (kind,)
                data["endpoints"] = [
                    endpoint for endpoint in endpoints if endpoint["kind"] in kinds
                ]
            result.append((section["title"], data))
        result[0][1]["includes"] = self.trait(self.service, "cppIncludes", [])
        listed = sum(len(data.get("endpoints", [])) for _, data in result)
        if listed != len(endpoints):
            raise SpecError(
                "every kind of endpoint needs a section in the docSections of the service"
            )
        return result


