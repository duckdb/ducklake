def topological_order(spec, objects):
    """Orders the DTOs so that every structure is declared after the structures it holds"""
    by_name = {obj.name: obj for obj in objects}
    order = []
    visited = set()

    def dependencies(expr, result, in_list=False):
        if expr.kind == "named" and expr.name in by_name:
            result.append((expr.name, in_list))
        for arg in expr.args:
            dependencies(arg, result, in_list or expr.kind == "list")

    def visit(obj, stack):
        if obj.name in visited:
            return
        if obj.name in stack:
            raise SpecError(f"Types {stack} hold each other")
        deps = []
        if obj.extends and obj.extends in by_name:
            deps.append((obj.extends, False))
        for field in obj.fields:
            dependencies(field.type, deps)
        for dep, in_list in deps:
            if in_list and (dep in stack or dep == obj.name):
                # a vector can hold the structure that holds it
                continue
            visit(by_name[dep], stack + [obj.name])
        visited.add(obj.name)
        order.append(obj)

    for obj in objects:
        visit(obj, [])
    return order


def write_field(spec, field, lines):
    if field.arrow_only:
        return
    member = f"value.{field.member}"
    expr = field.type
    if expr.kind == "map":
        key_codec = spec.codec(expr.args[0])
        value_codec = spec.codec(expr.args[1])
        lines.append(f"\t{{")
        lines.append(f"\t\tauto entries = writer.CreateArray();")
        lines.append(f"\t\tfor (auto &entry : {member}) {{")
        if field.value_field:
            lines.append(f"\t\t\tauto item = writer.CreateObject();")
            lines.append(
                f"\t\t\titem.Add({cpp_string(field.key_field)}, RESTWriteValue<{key_codec}>(writer, entry.first));"
            )
            lines.append(
                f"\t\t\titem.Add({cpp_string(field.value_field)}, "
                f"RESTWriteValue<{value_codec}>(writer, entry.second));"
            )
        else:
            lines.append(
                f"\t\t\tauto item = RESTWriteValue<{value_codec}>(writer, entry.second);"
            )
            lines.append(
                f"\t\t\titem.Add({cpp_string(field.key_field)}, RESTWriteValue<{key_codec}>(writer, entry.first));"
            )
        lines.append(f"\t\t\tentries.Append(item);")
        lines.append(f"\t\t}}")
        lines.append(f"\t\tresult.Add({cpp_string(field.name)}, entries);")
        lines.append(f"\t}}")
        return
    write = f"RESTWriteValue<{spec.codec(expr)}>(writer, {member})"
    if expr.kind == "primitive" and expr.name == "rows":
        write = f"RESTRowsCodec::Write(writer, {member})"
    add = f"result.Add({cpp_string(field.name)}, {write});"
    if field.has_member:
        lines.append(f"\tif (value.{field.has_member}) {{")
        lines.append(f"\t\t{add}")
        lines.append(f"\t}}")
    elif field.null_member:
        lines.append(f"\tif (!value.{field.null_member}) {{")
        lines.append(f"\t\t{add}")
        lines.append(f"\t}}")
    elif field.nullable:
        lines.append(f"\tif (!RESTIsNull({member})) {{")
        lines.append(f"\t\t{add}")
        lines.append(f"\t}}")
    else:
        lines.append(f"\t{add}")


def row_types_code(spec, obj, field):
    """The code that computes the types of the rows of a rows field"""
    parts = field.row_types.split(".")
    fields = {f.name: f for f in spec.fields_of(obj)}
    source = fields[parts[0]]
    if len(parts) == 1:
        return f"result.{source.member}"
    if source.type.kind != "list" or source.type.args[0].kind != "named":
        raise SpecError(
            f"{obj.name}.{field.name}: row_types can only refer to fields of a list of objects"
        )
    element = spec.types[source.type.args[0].name]
    element_fields = {f.name: f for f in spec.fields_of(element)}
    if parts[1] not in element_fields:
        raise SpecError(
            f'{obj.name}.{field.name}: {element.name} has no field "{parts[1]}"'
        )
    return f"RESTRowTypes(result.{source.member}, &{element.cpp_name}::{element_fields[parts[1]].member})"


def read_field(spec, obj, field, lines):
    if field.arrow_only:
        return
    member = f"result.{field.member}"
    expr = field.type
    required = not field.nullable and field.default is None
    get = "Get" if required else "TryGet"
    if expr.kind == "map":
        key_codec = spec.codec(expr.args[0])
        value_codec = spec.codec(expr.args[1])
        lines.append(
            f"\tfor (auto &item : in.{get}({cpp_string(field.name)}).Items()) {{"
        )
        lines.append(f"\t\tusing map_t = decltype({member});")
        lines.append(
            f"\t\tauto key = {key_codec}::template Get<typename map_t::key_type>("
            f"item.Get({cpp_string(field.key_field)}));"
        )
        item = (
            f"item.Get({cpp_string(field.value_field)})"
            if field.value_field
            else "item"
        )
        lines.append(
            f"\t\t{member}.emplace(key, {value_codec}::template Get<typename map_t::mapped_type>({item}));"
        )
        lines.append(f"\t}}")
        return
    if expr.kind == "primitive" and expr.name == "rows":
        read = f"RESTRowsCodec::Read({{entry}}, {member}, {row_types_code(spec, obj, field)});"
    else:
        read = f"RESTReadValue<{spec.codec(expr)}>({{entry}}, {member});"
    if required:
        lines.append("\t" + read.format(entry=f"in.Get({cpp_string(field.name)})"))
        return
    lines.append(f"\t{{")
    lines.append(f"\t\tauto entry = in.TryGet({cpp_string(field.name)});")
    if field.has_member:
        lines.append(f"\t\tresult.{field.has_member} = !entry.IsNull();")
        lines.append(f"\t\tif (result.{field.has_member}) {{")
    elif field.null_member:
        lines.append(f"\t\tresult.{field.null_member} = entry.IsNull();")
        lines.append(f"\t\tif (!result.{field.null_member}) {{")
    else:
        lines.append(f"\t\tif (!entry.IsNull()) {{")
    lines.append("\t\t\t" + read.format(entry="entry"))
    if field.default is not None and spec.default_literal(field) is not None:
        lines.append(f"\t\t}} else {{")
        lines.append(f"\t\t\t{member} = {spec.default_literal(field)};")
    lines.append(f"\t\t}}")
    lines.append(f"\t}}")


def doc_comment(text, indent):
    if not text:
        return []
    first = text.split("\n")[0]
    return [f"{indent}//! {first}"]


def generate_header(spec):
    lines = []
    lines.append(
        "//===----------------------------------------------------------------------===//"
    )
    lines.append("//                         DuckDB")
    lines.append("//")
    lines.append("// rest/ducklake_rest_api.hpp")
    lines.append("//")
    lines.append(f"// {GENERATED_NOTICE}")
    lines.append(
        "//===----------------------------------------------------------------------===//"
    )
    lines.append("")
    lines.append("#pragma once")
    lines.append("")
    includes = ["rest/ducklake_rest_codec.hpp"]
    for section in spec.sections:
        for include in section.includes:
            if include not in includes:
                includes.append(include)
    for include in includes:
        lines.append(f'#include "{include}"')
    lines.append("")
    lines.append("namespace duckdb {")
    lines.append("class ClientContext;")
    lines.append("class DuckLakeRESTRequest;")
    lines.append("struct RESTCommitRequest;")
    for union in spec.unions:
        lines.append(f"struct {union.cpp_name};")
    lines.append("")

    # enums
    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    lines.append("// Enums")
    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    for enum in spec.enums:
        lines.extend(doc_comment(enum.description, ""))
        lines.append(f"struct {enum.codec} : public RESTCodec<{enum.codec}> {{")
        lines.append(
            f'\tstatic const char *ToString({"const string &" if not enum.cpp_enum else enum.cpp_enum} value);'
        )
        lines.append(f"\tstatic {enum.cpp_name} FromString(const string &value);")
        lines.append(
            f"\tstatic JSONMutableValue Write(JSONWriter &writer, "
            f'{"const string &" if not enum.cpp_enum else enum.cpp_enum} value);'
        )
        lines.append(f"\tstatic void Read(RESTJsonIn in, {enum.cpp_name} &result);")
        lines.append(f"}};")
        lines.append("")

    # serializer
    all_objects = spec.all_objects()
    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    lines.append("// Serialization")
    lines.append(
        "//===--------------------------------------------------------------------===//"
    )
    for obj in all_objects:
        if not obj.is_bound:
            lines.append(f"struct {obj.cpp_name};")
    lines.append("")
    lines.append(
        "//! A part of an HTTP request besides its JSON document, e.g. a table as an Arrow IPC stream"
    )
    lines.append("struct RESTBodyPart {")
    lines.append("\tstring name;")
    lines.append("\tstring content;")
    lines.append("};")
    lines.append("")
    lines.append("//! A response of a server")
    lines.append("struct RESTHttpResponse {")
    lines.append("\tstring body;")
    lines.append("\tstring content_type;")
    lines.append("\t//! The context for the conversions of the body")
    lines.append("\toptional_ptr<ClientContext> context;")
    lines.append("};")
    lines.append("")
    lines.append("//! Conversion of the structures of the REST API to and from JSON")
    lines.append("struct DuckLakeRESTSerializer {")
    lines.append("\ttemplate <class T>")
    lines.append("\tstatic T Read(RESTJsonIn in);")
    lines.append("\t//! The JSON document of a structure")
    lines.append("\ttemplate <class T>")
    lines.append("\tstatic string ToJSON(const T &value) {")
    lines.append("\t\tRESTJsonWriter document;")
    lines.append("\t\tdocument.SetRoot(Write(document.writer, value));")
    lines.append("\t\treturn document.ToString();")
    lines.append("\t}")
    lines.append(
        "\t//! Reads the request of an endpoint from the body of an HTTP request, which is JSON unless the request has"
    )
    lines.append("\t//! parts besides the JSON document")
    lines.append("\ttemplate <class T>")
    lines.append(
        "\tstatic T ReadRequest(DuckLakeRESTRequest &request, const string &body) {"
    )
    lines.append("\t\tRESTJsonReader document(body);")
    lines.append("\t\treturn Read<T>(document.Root());")
    lines.append("\t}")
    lines.append(
        "\t//! The parts of the HTTP request of a client besides its JSON document"
    )
    lines.append("\ttemplate <class T>")
    lines.append(
        "\tstatic void AddParts(ClientContext &context, const T &value, vector<RESTBodyPart> &parts) {"
    )
    lines.append("\t}")
    lines.append(
        "\t//! The body of the response to a request: JSON, or another format that the request accepts"
    )
    lines.append("\ttemplate <class T>")
    lines.append("\tstatic string ToResponse(DuckLakeRESTRequest &request, T &value) {")
    lines.append("\t\treturn ToJSON(value);")
    lines.append("\t}")
    lines.append("\t//! Reads the body of a response of a content type")
    lines.append("\ttemplate <class T>")
    lines.append("\tstatic T ReadResponse(RESTHttpResponse &response) {")
    lines.append("\t\tRESTJsonReader document(response.body);")
    lines.append("\t\treturn Read<T>(document.Root());")
    lines.append("\t}")
    lines.append("")
    for obj in all_objects:
        lines.append(
            f"\tstatic JSONMutableValue Write(JSONWriter &writer, const {obj.cpp_name} &value);"
        )
    lines.append("};")
    lines.append("")
    for obj in all_objects:
        lines.append(f"template <>")
        lines.append(f"{obj.cpp_name} DuckLakeRESTSerializer::Read(RESTJsonIn in);")
