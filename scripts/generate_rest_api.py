class TypeExpr:
    def __init__(self, kind, name=None, args=None):
        # kind: primitive, named, list, dict, map
        self.kind = kind
        self.name = name
        self.args = args or []

    def __repr__(self):
        if self.kind in ("primitive", "named"):
            return self.name
        return f"{self.kind}<{', '.join(repr(arg) for arg in self.args)}>"


def split_type_args(text):
    args = []
    depth = 0
    current = ""
    for c in text:
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        if c == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += c
    args.append(current.strip())
    return args


def parse_type(text):
    text = text.strip()
    match = re.fullmatch(r"(list|dict|map)<(.*)>", text)
    if match:
        kind = match.group(1)
        args = [parse_type(arg) for arg in split_type_args(match.group(2))]
        expected = 2 if kind == "map" else 1
        if len(args) != expected:
            raise SpecError(f'"{text}": {kind} takes {expected} type argument(s)')
        return TypeExpr(kind, args=args)
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", text):
        raise SpecError(f'Invalid type "{text}"')
    if text in PRIMITIVES:
        return TypeExpr("primitive", name=text)
    return TypeExpr("named", name=text)


