        for value in enum.values:
            lines.append(f'\tif (value == {cpp_string(value["name"])}) {{')
            if enum.cpp_enum:
                lines.append(f'\t\treturn {enum.cpp_enum}::{value["cpp"]};')
            else:
                lines.append(f"\t\treturn value;")
            lines.append("\t}")
